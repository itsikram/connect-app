export const STRINGS: Record<RecoveryLang, Strings> = { en, bn };

// ---------------------------------------------------------------------------
// Language: follows the app language unless Recovery has its own override.
// ---------------------------------------------------------------------------
const OVERRIDE_KEY = '@connect/recovery-language';
let override: 'auto' | RecoveryLang = 'auto';
let overrideLoaded = false;
const listeners = new Set<(value: 'auto' | RecoveryLang) => void>();

export const setRecoveryLanguage = async (value: 'auto' | RecoveryLang) => {
  override = value;
  listeners.forEach((listener) => listener(value));
  try {
    await AsyncStorage.setItem(OVERRIDE_KEY, value);
  } catch (_) {
    // Preference only; the app language still applies.
  }
};

const BN_DIGITS = '০১২৩৪৫৬৭৮৯';
export const toLocalDigits = (value: string, lang: RecoveryLang) => (lang === 'bn' ? value.replace(/\d/g, (digit) => BN_DIGITS[Number(digit)]) : value);

/** Groups like 1,00,000 (lakh style, as used in Bangladesh). */
const groupNumber = (value: number) => {
  const rounded = String(Math.round(Math.abs(value)));
  if (rounded.length <= 3) return rounded;
  const head = rounded.slice(0, -3).replace(/\B(?=(\d{2})+(?!\d))/g, ',');
  return `${head},${rounded.slice(-3)}`;
};

/** Fills {name} placeholders. */
export const fill = (template: string, values: Record<string, string | number> = {}) =>
  template.replace(/\{(\w+)\}/g, (match, key) => (values[key] !== undefined ? String(values[key]) : match));

export const makeFormatters = (lang: RecoveryLang) => {
  const num = (value: number | null | undefined, decimals = 0) => {
    const number = Number(value) || 0;
    const text = decimals ? number.toFixed(decimals) : groupNumber(number);
    return toLocalDigits(`${number < 0 ? '-' : ''}${text}`, lang);
  };
  const money = (value: number | null | undefined) => `৳${num(value)}`;
  const date = (value: string | number | Date, options: Intl.DateTimeFormatOptions = { day: 'numeric', month: 'short', year: 'numeric' }) => {
    const parsed = new Date(value);
    try {
      return parsed.toLocaleDateString(lang === 'bn' ? 'bn-BD' : 'en-GB', options);
    } catch (_) {
      return toLocalDigits(parsed.toDateString(), lang);
    }
  };
  /** "3d 4h" style duration for small labels. */
  const duration = (ms: number) => {
    const s = STRINGS[lang].common;
    const totalMinutes = Math.max(0, Math.floor(ms / 60000));
    const days = Math.floor(totalMinutes / 1440);
    const hours = Math.floor((totalMinutes % 1440) / 60);
    const minutes = totalMinutes % 60;
    if (days) return `${num(days)} ${s.days} ${num(hours)} ${s.hours}`;
    if (hours) return `${num(hours)} ${s.hours} ${num(minutes)} ${s.minutes}`;
    return `${num(minutes)} ${s.minutes}`;
  };
  return { num, money, date, duration };
};

export const useRecoveryI18n = () => {
  const { settings } = useSettings();
  const [current, setCurrent] = useState(override);

  useEffect(() => {
    listeners.add(setCurrent);
    if (!overrideLoaded) {
      overrideLoaded = true;
      AsyncStorage.getItem(OVERRIDE_KEY)
        .then((stored) => {
          if (stored === 'en' || stored === 'bn' || stored === 'auto') {
            override = stored;
            listeners.forEach((listener) => listener(stored));
          }
        })
        .catch(() => {});
    }
    return () => {
      listeners.delete(setCurrent);
    };
  }, []);

  const lang: RecoveryLang = current === 'auto' ? (settings?.language === 'bn' ? 'bn' : 'en') : current;
  return useMemo(() => ({ lang, override: current, s: STRINGS[lang], f: fill, ...makeFormatters(lang) }), [lang, current]);
};
